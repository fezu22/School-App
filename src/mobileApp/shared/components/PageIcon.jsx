export function getPageIconName(name) {
  return pageIconNames[name] || (iconSources[name] ? name : 'file');
}

export default function PageIcon({
  name = 'file',
  size = 24,
  color = '#4857B5',
  style,
  accessibilityLabel,
}) {
  return (
    <Image
      source={iconSources[getPageIconName(name)]}
      resizeMode="contain"
      accessible={!!accessibilityLabel}
      accessibilityLabel={accessibilityLabel}
      importantForAccessibility={accessibilityLabel ? 'yes' : 'no'}
      fadeDuration={0}
      style={[{ width: size, height: size, tintColor: color }, style]}
    />
  );
}
