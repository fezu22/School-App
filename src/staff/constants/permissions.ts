export const hasPermission = (
  userRole: UserRole | undefined | null,
  permission: Permission,
): boolean => {
  if (!userRole) return false;
  const userPerms = ROLE_PERMISSIONS[userRole];
  return userPerms ? userPerms.includes(permission) : false;
};
